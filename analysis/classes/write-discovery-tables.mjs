import fs from 'node:fs';

const directory = 'analysis/classes';
const read = filename => JSON.parse(fs.readFileSync(`${directory}/${filename}`, 'utf8'));
const evidence = read('source-evidence.json');
const mechanics = read('mechanics-evidence.json');
const references = read('cross-catalog-references.json');
const inventory = read('normalized-field-inventory.json');
const graph = read('feature-graph.json');
const inheritance = read('inheritance-evidence.json');
const summary = evidence.summary;
const roots = mechanics.classesAndSubclasses;
const classes = roots.filter(record => record.kind === 'class');
const subclasses = roots.filter(record => record.kind === 'subclass');
const count = values => Object.fromEntries(values.reduce((counts, value) => {
    counts.set(value, (counts.get(value) ?? 0) + 1);
    return counts;
}, new Map()));
const escape = value => String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const table = (headers, rows) => [
    '| ' + headers.join(' | ') + ' |',
    '| ' + headers.map(() => '---').join(' | ') + ' |',
    ...rows.map(row => '| ' + row.map(escape).join(' | ') + ' |'),
].join('\n');
const sections = ['# Classes Stage A discovery tables',
    'Generated by `node analysis/classes/write-discovery-tables.mjs` after `discover-classes.mjs`. '
    + 'Counts describe authored roots and declarations, without copy/version expansion.'];

sections.push('## Physical files', table(['File', 'Class', 'Subclass', 'Class feature', 'Subclass feature', '_meta'],
    evidence.files.map(file => [file.file, ...['class', 'subclass', 'classFeature', 'subclassFeature', '_meta']
        .map(kind => file.roots[kind]?.count ?? 0)])));
const sources = [...new Set(Object.values(summary.byKindAndSource).flatMap(value => Object.keys(value)))].sort();
sections.push('## Primary source distribution', table(['Source', 'Class', 'Subclass', 'Class feature', 'Subclass feature'],
    sources.map(source => [source, ...['class', 'subclass', 'classFeature', 'subclassFeature']
        .map(kind => summary.byKindAndSource[kind][source] ?? 0)])));
sections.push('## Class identities and subclass advancement', table([
    'Class', 'Source', 'Declared edition', 'Subclass advancement levels', 'Hit die', 'Caster code', 'Ability',
], classes.map(({data}) => [data.name, data.source, data.edition,
    data.classFeatures.filter(feature => feature.gainSubclassFeature)
        .map(feature => feature.classFeature.split('|')[3]).join(', ') || '(absent)',
    data.hd ? `${data.hd.number}d${data.hd.faces}` : '(absent)', data.casterProgression, data.spellcastingAbility])));

sections.push('## Root fields', 'Nested fields, missing counts, every object shape, source distributions, '
    + 'and declared edition distributions are in `normalized-field-inventory.json`.');
for (const kind of ['class', 'subclass', 'classFeature', 'subclassFeature']) {
    const rootFields = inventory.fields.filter(field => field.path.startsWith(`${kind}[].`)
        && !field.path.endsWith('[]')
        && !field.path.slice(kind.length + 3).includes('.'));
    sections.push(`### ${kind}`, table(['Field', 'Occurrences', 'JSON types', 'Missing', 'Category'],
        rootFields.map(field => [field.path, field.occurrences, JSON.stringify(field.types),
            field.missingFromParentObjects, field.category])));
}

const tables = roots.flatMap(record => (record.data.classTableGroups ?? record.data.subclassTableGroups ?? [])
    .map((group, index) => ({owner: record.locator, index, kind: record.kind,
        name: record.data.name, source: record.data.source, parentSource: record.data.classSource,
        columns: group.colLabels, rows: group.rows ?? group.rowsSpellProgression,
        rowKind: group.rowsSpellProgression ? 'rowsSpellProgression' : 'rows'})));
sections.push('## Progression table groups', 'Each row here is an owned table group, not a reusable definition. '
    + 'All observed table groups have 20 rows. Zero-based source row 0 corresponds to level 1; '
    + 'public level associations should use explicit level numbers.',
table(['Owner', 'Source', 'Parent source', 'Group', 'Row kind', 'Rows', 'Columns'], tables.map(group => [
    group.name, group.source, group.parentSource, group.index, group.rowKind, group.rows.length,
    group.columns.join(' / '),
])));
sections.push('## Entry discriminators',
    'Counts include root feature rendering types as well as nested entries and typed table cells.',
    table(['Type', 'Occurrences', 'All field sets'],
    Object.entries(mechanics.entryTypes).map(([type, details]) => [type, details.count,
        Object.entries(details.shapes).map(([shape, occurrences]) => `${shape} (${occurrences})`).join(' / ')])));
sections.push('## Structured external references', table(['Kind', 'Status', 'Occurrences'],
    Object.entries(summary.foreignResolutionCounts).map(([key, occurrences]) => [...key.split(':'), occurrences])));
sections.push('## Markup references and directives', table(['Tag', 'Occurrences'], Object.entries(summary.markupTagCounts)));
sections.push('## Source Registry coverage', table(['Written code', 'Registry identity', 'Occurrences'],
    read('source-registry-coverage.json').sources.map(source => [source.code, source.canonicalCode, source.occurrences])));

const details = {
    rootEditionCounts: Object.fromEntries(['class', 'subclass'].map(kind => [kind,
        count(roots.filter(record => record.kind === kind).map(record => record.data.edition ?? '(absent)'))])),
    subclassParentSourceCounts: count(subclasses.map(record => record.data.classSource)),
    copyTransitions: count(inheritance.directives.map(directive => {
        const owner = evidence.definitions.find(record => record.locator === directive.owner);
        const parentSource = owner.identity.split('|')[2];
        return `${directive.kind}:${directive.value.classSource.toLowerCase()}->${parentSource}`;
    })),
    tableGroupCounts: count(tables.map(group => `${group.kind}:${group.rowKind}`)),
    tableRowLengthCounts: count(tables.map(group => group.rows.length)),
    ordinaryCellTypes: count(tables.filter(group => group.rowKind === 'rows').flatMap(group => group.rows.flat())
        .map(value => value && typeof value === 'object' ? value.type : typeof value)),
    casterCodes: Object.fromEntries(['class', 'subclass'].map(kind => [kind,
        count(roots.filter(record => record.kind === kind && record.data.casterProgression)
            .map(record => record.data.casterProgression))])),
    spellQualification: count(references.foreignResolution.filter(reference => reference.kind === 'spell')
        .map(reference => reference.sourceExplicit ? 'qualified' : 'unqualified')),
    spellSelectorCount: references.selectors.length,
    spellSelectorDistinctCount: new Set(references.selectors.map(reference => reference.expression)).size,
    unresolvedForeignReferences: references.foreignResolution.filter(reference => reference.status === 'unresolved'),
    classRootFieldNames: Object.keys(summary.rootFields.class),
    allFeatureCount: evidence.definitions.filter(record => record.kind.endsWith('Feature')).length,
    graphEdges: graph.edges.length,
    copyTargetsAlsoCopies: graph.edges.filter(edge => edge.relation === 'copy'
        && edge.targets.some(target => graph.edges.some(candidate => candidate.owner === target && candidate.relation === 'copy'))).length,
};
fs.writeFileSync(`${directory}/DISCOVERY-TABLES.md`, sections.join('\n\n') + '\n');
fs.writeFileSync(`${directory}/summary-details.json`, JSON.stringify(details, null, 2) + '\n');
console.log(JSON.stringify(details, null, 2));
